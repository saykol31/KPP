int main()
{
    int x = 10;
    int y = 20;

    if (x < y)
    {
        print("LT OK");
    }

    if (x <= y)
    {
        print("LE OK");
    }

    if (x == 10)
    {
        print("EQ OK");
    }

    if (x != y)
    {
        print("NE OK");
    }

    if (y >= x)
    {
        print("GE OK");
    }

    return x;
}
